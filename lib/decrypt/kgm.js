// ── 音频格式探测 ─────────────────────────────────────────────────────────────

const FLAC_HDR = [0x66, 0x4c, 0x61, 0x43] // fLaC
const MP3_HDR = [0x49, 0x44, 0x33] // ID3
const OGG_HDR = [0x4f, 0x67, 0x67, 0x53] // OggS
const M4A_HDR = [0x66, 0x74, 0x79, 0x70] // ftyp（位于偏移 4）
const WMA_HDR = [0x30, 0x26, 0xb2, 0x75, 0x8e, 0x66, 0xcf, 0x11, 0xa6, 0xd9, 0x00, 0xaa, 0x00, 0x62, 0xce, 0x6c]
const WAV_HDR = [0x52, 0x49, 0x46, 0x46] // RIFF
const DFF_HDR = [0x46, 0x52, 0x4d, 0x38] // FRM8

function startsWith(a, b, off = 0) {
  if (a.length < off + b.length) return false
  for (let i = 0; i < b.length; i++) if (a[off + i] !== b[i]) return false
  return true
}

/**
 * 从解密后的音频头部猜容器格式。
 * 优先吃 lib/ncm-decryptor.js 的 sniffAudioFormat（保持两处格式判定一致），
 * 它不认识的（wma / aac / dff）再走本地兜底表。全都不认识时返回 null 让上层报错，
 * **不**默认成 mp3 —— 默认 mp3 会把解密失败伪装成成功。
 * @param {Uint8Array} audio
 * @returns {string|null}
 */
export function inferFormat(audio) {
  if (!audio || audio.length < 4) return null
  const s = sniffAudioFormat(Buffer.from(audio.buffer, audio.byteOffset, audio.byteLength))
  if (s) return s
  if (startsWith(audio, WMA_HDR)) return 'wma'
  if (audio[0] === 0xff && audio[1] === 0xf1) return 'aac'
  if (startsWith(audio, DFF_HDR)) return 'dff'
  return null
}

// ── 掩码函数 ─────────────────────────────────────────────────────────────────

/**
 * 按音频全局位置算掩码字节。
 * @param {number} pos 音频内的全局偏移（不含头部）
 * @returns {number}
 */
function getMask(pos) {
  let offset = pos >> 4
  let value = 0
  while (offset >= 0x11) {
    value ^= TABLE1[offset % 272]
    offset >>= 4
    value ^= TABLE2[offset % 272]
    offset >>= 4
  }
  return MASK_V2_PRE_DEF[pos % 272] ^ value
}

/**
 * 原地解密一段音频。
 * @param {Uint8Array} data 待解密数据（会被改写）
 * @param {Uint8Array} key 17 字节密钥
 * @param {boolean} isVpr 是否 VPR 格式
 * @param {number} startOffset 这段数据在整条音频中的起始偏移（流式分块必须传对）
 */
export function decryptChunk(data, key, isVpr, startOffset) {
  for (let i = 0; i < data.length; i++) {
    const pos = startOffset + i
    let med8 = key[pos % 17] ^ data[i]
    med8 ^= (med8 & 0x0f) << 4
    let msk8 = getMask(pos)
    msk8 ^= (msk8 & 0x0f) << 4
    let b = med8 ^ msk8
    if (isVpr) b ^= VPR_MASK_DIFF[pos % 17]
    data[i] = b
  }
}

// ── 文件头解析 ───────────────────────────────────────────────────────────────

/**
 * 解析 KGM/VPR 头部，拿到 isVpr / headerLen / 17 字节密钥。
 * @param {Uint8Array} prefix 文件前 0x2C 字节
 */
export function parseHeader(prefix) {
  if (!prefix || prefix.length < 0x2c) {
    throw new Error(`KGM/VPR: 文件过短（${prefix ? prefix.length : 0} < 0x2C）`)
  }
  let isVpr
  if (startsWith(prefix, KGM_HEADER)) isVpr = false
  else if (startsWith(prefix, VPR_HEADER)) isVpr = true
  else throw new Error('KGM/VPR: magic 不匹配，不是 KGM/KGMA/VPR 文件')

  const headerLen = (prefix[0x10] | (prefix[0x11] << 8) | (prefix[0x12] << 16) | (prefix[0x13] << 24)) >>> 0
  if (headerLen < 0x2c) throw new Error(`KGM/VPR: 头部长度异常 ${headerLen}`)

  const key = new Uint8Array(17)
  key.set(prefix.subarray(0x1c, 0x2c), 0)
  key[16] = 0
  return { isVpr, headerLen, key }
}

// ── 主入口 ───────────────────────────────────────────────────────────────────

/**
 * 解密 KGM/KGMA/VPR 文件到 outputPath。
 *
 * 流式实现：读 64KB → 原地解密 → 写 64KB，全程只持有一个块的内存，
 * 手机上解几十兆的 FLAC 也不会 OOM。输出先写 `.xxx.oc-partial` 临时文件，
 * 成功探测到格式后才 rename 成最终文件，失败则删临时文件——不会留半截音频。
 *
 * @param {string} inputPath .kgm / .kgma / .vpr 文件
 * @param {string} outputPath 目标路径；无扩展名时按探测结果补
 * @returns {Promise<{ok:boolean, output?:string, format?:string, meta?:object|null,
 *   audioBytes?:number, error?:string}>}
 */
export async function decryptFile(inputPath, outputPath) {
  let fd = null
  let outFd = null
  let tmpPath = null
  try {
    const stat = statSync(inputPath)
    if (!stat.isFile()) return { ok: false, input: inputPath, error: 'KGM/VPR: 输入不是普通文件' }
    if (stat.size < 0x2c) return { ok: false, input: inputPath, error: `KGM/VPR: 文件过短（${stat.size} < 0x2C）` }

    fd = openSync(inputPath, 'r')
    const prefix = Buffer.alloc(0x2c)
    if (readSync(fd, prefix, 0, 0x2c, 0) < 0x2c) {
      return { ok: false, input: inputPath, error: 'KGM/VPR: 读取文件头失败' }
    }
    const { isVpr, headerLen, key } = parseHeader(prefix)
    if (headerLen > stat.size) {
      return { ok: false, input: inputPath, error: `KGM/VPR: 头部长度 ${headerLen} 超出文件大小 ${stat.size}` }
    }

    const outBase = String(outputPath || '')
    if (outBase === '') return { ok: false, input: inputPath, error: 'KGM/VPR: 输出路径为空' }
    // 与 ncm-decryptor 一致：调用方给无扩展名路径时按探测格式补，给了就照用
    const hasExt = /\.[^./\\]+$/.test(outBase)
    const dir = outBase.replace(/[\\/][^\\/]*$/, '') || '.'
    mkdirSync(dir, { recursive: true })

    tmpPath = join(dir, `.${basename(outBase)}.kgm-partial`)
    outFd = openSync(tmpPath, 'w')

    const buf = Buffer.alloc(CHUNK)
    let audioOffset = 0
    let filePos = headerLen
    let probe = Buffer.alloc(0)

    while (filePos < stat.size) {
      const want = Math.min(CHUNK, stat.size - filePos)
      const n = readSync(fd, buf, 0, want, filePos)
      if (n <= 0) break
      const chunk = buf.subarray(0, n)
      decryptChunk(chunk, key, isVpr, audioOffset)
      if (probe.length < 16) probe = Buffer.concat([probe, chunk.subarray(0, Math.min(n, 16 - probe.length))])
      writeSync(outFd, chunk, 0, n)
      audioOffset += n
      filePos += n
    }
    closeSync(outFd)
    outFd = null

    if (audioOffset === 0) {
      return { ok: false, input: inputPath, error: 'KGM/VPR: 音频段长度为 0' }
    }

    const format = inferFormat(probe)
    if (!format) {
      return {
        ok: false,
        input: inputPath,
        error: 'KGM/VPR: 解密后的数据不是可识别的音频流（密钥可能与文件不匹配）',
      }
    }

    const finalPath = hasExt ? outBase : `${outBase}.${format}`
    renameSync(tmpPath, finalPath)
    tmpPath = null
    closeSync(fd)
    fd = null

    // KGM 容器内不嵌歌曲元数据（只有密钥），meta 恒为 null，
    // 由 lib/decrypt/index.js 的 normalizeMeta 回退到文件名。
    return {
      ok: true,
      input: inputPath,
      output: finalPath,
      format,
      meta: null,
      audioBytes: audioOffset,
    }
  } catch (e) {
    return { ok: false, input: inputPath, error: `KGM/VPR 解密失败：${e?.message ?? e}` }
  } finally {
    if (outFd != null) {
      try { closeSync(outFd) } catch {}
    }
    if (fd != null) {
      try { closeSync(fd) } catch {}
    }
    if (tmpPath != null) {
      try { unlinkSync(tmpPath) } catch {}
    }
  }
}

