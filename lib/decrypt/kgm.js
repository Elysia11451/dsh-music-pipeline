// lib/decrypt/kgm.js — 酷狗 KGM / KGMA / VPR 解密器
//
// 遵守统一解密器契约（见 ncm.js 顶部注释）：
//   FORMATS / LABEL / decryptFile(inputPath, outputPath) -> Promise<Result>
//
// 算法事实与常量表来源
//   移植自 OpenConverter (nowa277/OpenConverter, Apache-2.0) 的 KGM/KGMA/VPR 解码器，
//   其自述基于 huangbao/MyKgmWasm (MIT)。纯 JS，无原生依赖，无浏览器依赖。
//   上游 Unlock Music (unlock-music/unlock-music, MIT) 已因 DMCA 被 GitHub 下架，
//   故本文件以 OpenConverter 的 Apache-2.0 实现为移植基准，并在此完整署名。
//
// 文件布局
//   0x00..0x10  16 字节 magic：KgmHeader（KGM/KGMA）或 VprHeader（VPR）
//   0x10..0x14  uint32 LE 头部长度 headerLen
//   0x14..0x1C  4 字节保留
//   0x1C..0x2C  16 字节逐文件 AES 风格密钥（key[16] 隐式为 0）
//   0x2C..headerLen  保留
//   headerLen..end  加密音频
//
// 解密（按音频内偏移 i，pos = 全局音频位置）：
//   med8 = key[pos % 17] ^ data[i]
//   med8 ^= (med8 & 0x0F) << 4
//   msk8 = getMask(pos)
//   msk8 ^= (msk8 & 0x0F) << 4
//   data[i] = med8 ^ msk8
//   if isVpr: data[i] ^= VPR_MASK_DIFF[pos % 17]
//
// getMask(pos):
//   offset = pos >> 4; value = 0
//   while offset >= 0x11:
//     value ^= TABLE1[offset % 272]; offset >>= 4
//     value ^= TABLE2[offset % 272]; offset >>= 4
//   return MASK_V2_PRE_DEF[pos % 272] ^ value
//
// 注意：魔数表（KGM/VPR magic、VPR_MASK_DIFF）与三张 272 字节掩码表由
// scripts/gen-decrypt-tables.cjs 从参考实现程序化提取生成，**不要手改**。
// 改动方式：更新生成脚本后重跑。
